from __future__ import annotations

from typing import Optional

from pydantic import BaseModel, Field

class RetrieveProviderInfo(BaseModel):
    providerFirstName: str = Field(..., description="Provider's first name.")
    providerLastName: str = Field(..., description="Provider's last name.")
    tin: str = Field(..., description="The provider's Tax Identification Number. TIN is validated to ensure that it is neither blank nor blocked.")
    start: str = Field(..., description="The start index of the search results. Start is validated to ensure that it is neither blank nor less than 0.")
    
class SearchProviderInformation(BaseModel):
    memberId: str = Field(..., description="Member Identifier. MemberId is validated to ensure that it is not blank.")
    policyNumber: Optional[str] = Field(None, description="Policy Number. PolicyNumber is validated to ensure that it is not blank.")
    dateOfBirth: str = Field(..., description="Date of birth. Must be in yyyy-MM-dd format. Date of Birth is validated to ensure that it is not blank.")
    firstName: str = Field(..., description="First name. First Name is validated to ensure that it is not blank.")
    firstDateOfService: str = Field(..., description="First date of service. Must be in yyyy-MM-dd format. FirstDateOfService is validated to ensure that it is not blank.")
    lastDateOfService: str = Field(..., description="Last date of service. Must be in yyyy-MM-dd format. LastDateOfService is validated to ensure that it is not blank.")
    radius: str = Field(..., description="Radius. Radius is validated to ensure that it is not blank.")
    page: Optional[str] = Field(None, description="Page")
    key: Optional[str] = Field(None, description="Key")
    providerFirstName: Optional[str] = Field(None, description="Provider's first name.")
    providerLastName: Optional[str] = Field(None, description="Provider's last name.")
    providerSpeciality: Optional[str] = Field(None, description="Provider's speciality.")
    providerGender: Optional[str] = Field(None, description="Provider's gender.")
    providerBusinessSubCategory: Optional[str] = Field(None, description="Provider's business sub-category.")
    zipCode: str = Field(..., description="Zip Code. ZipCode is validated to ensure that it is not blank.")
    npi: Optional[str] = Field(None, description="National Provider Identifier.")
    start: Optional[str] = Field(None, description="Starting point to read results from.")
    payerId: Optional[str] = Field(None, description="Payer Identifier.")
    langCode: Optional[str] = Field(None, description="Language Code.")

class GetReferralStatus(BaseModel):
    memberId: str = Field(..., description="Member Identifier. MemberId is validated to ensure that it is not blank.")
    policyNumber: Optional[str] = Field(None, description="The member's policy number.")
    patientDob: str = Field(..., description="Patient Date of Birth. Must be in yyyy-MM-dd format. PatientDob is validated to ensure that it is not blank.")
    firstName: Optional[str] = Field(None, description="The member's first name. First Name is validated to ensure that it is not blank.")
    firstServiceDt: str = Field(..., description="The first date of service. Must be passed in the request in yyyy-MM-dd format. First Date of Service is validated to ensure that it is not blank. Please note that the First Date of Service must be an earlier date than the Last Date of Service.")
    lastServiceDt: str = Field(..., description="The last date of service. Must be passed in the request in yyyy-MM-dd format. Last Date of Service is validated to ensure that it is not blank. Please note that the Last Date of Service must be a later date than the First Date of Service.")
    payerId: str = Field(..., description="The payer's identification number. Payer ID is validated to ensure that it is not blank.")
    status: Optional[str] = Field(None, description="The desired referral status to search for.")

class ReferralSubmissionRequest(BaseModel):
    recordId: Optional[str] = Field(None, description="The record's identification number.")
    payerIndustryId: str = Field(..., description="The payer's identification number.")
    payerName: str = Field(..., description="The payer's name.")
    referralVersionCode: Optional[str] = Field(None, description="The referral version code.")
    requesterNpi: str = Field(..., description="The requester's National Provider Identifier (NPI).")
    requesterTin: str = Field(..., description="The requester's Tax Identification Number. If Requester TIN is passed in the request, it is validated to ensure that the TIN is not blocked. If the TIN is blocked, a TIN validation error message will be returned.")
    requesterFirstName: Optional[str] = Field(None, description="The requester's first name.")
    requesterLastName: Optional[str] = Field(None, description="The requester's last name.")
    requesterContactName: str = Field(..., description="The requester's contact name.")
    requesterContactPhNbr: str = Field(..., description="The requester's contact phone number.")
    patientLn: str = Field(..., description="The patient's last name.")
    patientFn: str = Field(..., description="The patient's first name.")
    patientMi: Optional[str] = Field("", description="The patient's middle initial.")
    patientDob: str = Field(..., description="The patient's date of birth. Must be in yyyy-MM-dd format.")
    patientMemberId: str = Field(..., description="The patient's member identification number.")
    patientGender: str = Field(..., description="The patient's gender.")
    patientGroupNbr: str = Field(..., description="The patient's group number.")
    patientRelationship: str = Field(..., description="The patient's relationship to the subscriber.")
    referredNpi: str = Field(..., description="The referred provider's National Provider Identifier (NPI).")
    numberOfVisits: str = Field(..., description="The number of visits.")
    getsubmissionComments: Optional[str] = Field(None, description="Submission Comment without special characters.")
    subscriberFn: Optional[str] = Field(None, description="The subscriber's first name.")
    subscriberLn: Optional[str] = Field(None, description="The subscriber's last name.")
    subscriberDob: Optional[str] = Field(None, description="The subscriber's date of birth.")
    subscriberGender: Optional[str] = Field(None, description="The subscriber's gender.")
    referredFn : str = Field(..., description="The referred provider's first name.")
    referredLn : str = Field(..., description="The referred provider's last name.")
    referredPhNbr : str = Field(..., description="The referred provider's phone number.")
    serviceStartDt : str = Field(..., description="The service start date. Must be passed in the request in yyyyMMdd format.")
    serviceEndDt : str = Field(..., description="The service end date. Must be passed in the request in yyyyMMdd format.")
    diagDiagnosis1 : str = Field(..., description="The first diagnosis code.")
    diagDiagnosis2 : str = Field(..., description="The second diagnosis code.")
    referredTin : str = Field(..., description="The referred provider's Tax Identification Number (TIN).")
    referredMpin : str = Field(..., description="The referred provider's MPIN.")
    referredCity : str = Field(..., description="The referred provider's city.")
    referredState : str = Field(..., description="The referred provider's state.")
    referredZip : str = Field(..., description="The referred provider's zip code.")
    referredAddrLn1 : str = Field(..., description="The referred provider's address line 1.")
    referredAddrLn2 : Optional[str] = Field("", description="The referred provider's address line 2.")
    requesterAddrLn1 : str = Field(..., description="The requester's address line 1.")
    requesterMpin : str = Field(..., description="The requester's MPIN.")
    requesterCity : str = Field(..., description="The requester's city.")
    requesterState : str = Field(..., description="The requester's state.")
    requesterZip : str = Field(..., description="The requester's zip code.")
    platform : Optional[str] = Field(None, description="Platform internal to UHC.")
    providerUUID : Optional[str] = Field(None)
    backendEnv: Optional[str] = Field(None)